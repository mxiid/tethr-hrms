/* global console, process */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

// Builds the PDF templates' Tailwind stylesheet from the template sources and
// commits it as a TS module, so PDF rendering needs no network and no
// build-time CSS pipeline. Run when the PDF templates' classes change:
//   npm run build:pdf-styles -w @hrms/api
const packageRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const inputPath = join(packageRoot, 'scripts', 'pdf-styles.input.css');
const outputPath = join(packageRoot, 'src', 'core', 'pdf', 'pdf-styles.generated.ts');
const temporaryDirectory = mkdtempSync(join(tmpdir(), 'hrms-pdf-styles-'));
const cssPath = join(temporaryDirectory, 'pdf-styles.css');

try {
  const npx = process.platform === 'win32' ? 'npx.cmd' : 'npx';
  execFileSync(
    npx,
    [
      '--yes',
      'tailwindcss@2.2.19',
      '-c',
      'tailwind.pdf.config.cjs',
      '-i',
      inputPath,
      '-o',
      cssPath,
      '--minify',
    ],
    { cwd: packageRoot, stdio: 'inherit', shell: process.platform === 'win32' },
  );

  const css = readFileSync(cssPath, 'utf8');
  writeFileSync(
    outputPath,
    [
      '// Generated by `npm run build:pdf-styles` — do not edit by hand.',
      '// Tailwind 2.2.19 compiled for the PDF templates; committed so rendering',
      '// needs no network access and no build-time CSS pipeline.',
      `export const PDF_STYLESHEET = ${JSON.stringify(css)};`,
      '',
    ].join('\n'),
    'utf8',
  );
  console.log(`Wrote ${outputPath} (${css.length} bytes)`);
} finally {
  rmSync(temporaryDirectory, { recursive: true, force: true });
}
